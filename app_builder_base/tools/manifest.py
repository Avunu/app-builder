"""Read and write ``__manifest__.py`` deterministically."""

import ast
import json

# Emission order for manifest keys. Anything not listed follows, alphabetically.
KEY_ORDER = (
    "name",
    "summary",
    "description",
    "version",
    "category",
    "website",
    "author",
    "license",
    "installable",
    "application",
    "auto_install",
    "depends",
    "external_dependencies",
    "data",
    "demo",
    "assets",
    "post_init_hook",
    "uninstall_hook",
)

_ORDER_INDEX = {key: i for i, key in enumerate(KEY_ORDER)}

HEADER = (
    "# Generated by App Builder. Safe to edit by hand:\n"
    "# the builder re-reads this file and preserves unknown keys.\n"
)


def read_manifest(path):
    """Parse a manifest with ``ast.literal_eval``, as Odoo itself does."""
    with open(path, encoding="utf-8") as handle:
        return ast.literal_eval(handle.read())


def _py(value):
    """Render a literal with double quotes.

    Matters more than it looks: a project that runs ``ruff format`` (this one
    does, via pre-commit) would rewrite single-quoted output on the next commit,
    and the package would then report as drifted even though nobody changed
    anything. Emitting already-canonical source keeps formatting a no-op.
    """
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return repr(value)


def _format_value(value, level=1):
    pad = "    " * level
    inner_pad = "    " * (level + 1)
    if isinstance(value, (list, tuple)):
        if not value:
            return "[]"
        items = "".join(
            "%s%s,\n" % (inner_pad, _format_value(item, level + 1)) for item in value
        )
        return "[\n%s%s]" % (items, pad)
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = "".join(
            "%s%s: %s,\n" % (inner_pad, _py(key), _format_value(value[key], level + 1))
            for key in sorted(value)
        )
        return "{\n%s%s}" % (items, pad)
    return _py(value)


def render_manifest(values):
    """Render a manifest dict to source text.

    ``data`` is emitted in the order given (load order is semantic and must not
    be sorted); every other collection is already normalised by the caller.
    """
    ordered = sorted(
        values.items(),
        key=lambda kv: (_ORDER_INDEX.get(kv[0], len(KEY_ORDER)), kv[0]),
    )
    body = "".join(
        "    %s: %s,\n" % (_py(key), _format_value(value)) for key, value in ordered
    )
    return "%s{\n%s}\n" % (HEADER, body)


def merge_manifest(existing, generated):
    """Overlay generated keys onto a hand-edited manifest.

    Keys the builder does not own (``post_init_hook``, custom flags, ...) are
    preserved, so a developer can hand-edit the manifest without the next write
    clobbering their work. That round-trip tolerance is the whole reason this
    module reads before it writes.
    """
    merged = dict(existing or {})
    merged.update(generated)
    return merged
