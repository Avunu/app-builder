"""Generate the pre-migration that keeps a removed field's data.

Measured, not assumed (``tests/e2e/probe_reimport.py``): dropping a field from
a generated model file **drops its column and its data**. Reflection stops
reflecting the field, ``_process_end`` unlinks the ``ir.model.fields`` row, and
``IrModelFields.unlink`` calls ``_drop_column`` -- which issues
``ALTER TABLE ... DROP COLUMN ... CASCADE``, taking the m2m relation table too.

That is ordinary Odoo behaviour for any addon, and the builder cannot change it.
What it can do is get there first. ``migrate_module(package, 'pre')`` runs at
``loading.py`` well before ``_process_end``, so a pre-migration that renames the
column aside leaves nothing for ``_drop_column`` to find: it drops no column,
the metadata row is correctly removed, and the data survives under a name a
human can go and look at.

Pure string generation, no ``odoo`` import, so it is testable without a
database.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable

HEADER = (
    "# Generated by App Builder.\n"
    "#\n"
    "# Removing a field from a model drops its column and its data. This runs\n"
    "# before Odoo gets there and renames the column (or, for a many2many, its\n"
    "# relation table) aside instead, so nothing is lost -- inspect it, then\n"
    "# drop it by hand when you are sure.\n"
)


def suffix_for(stamp: str) -> str:
    """A stable, sortable, obviously-not-a-real-field suffix."""
    return "builder_removed_%s" % stamp


def rename_column_sql(table: str, column: str, suffix: str) -> str:
    new = "%s_%s" % (column, suffix)
    # 63 is the Postgres identifier limit; truncating the *original* part keeps
    # the marker, which is what makes the leftover findable.
    if len(new) > 63:
        keep = 63 - len(suffix) - 1
        new = "%s_%s" % (column[:keep], suffix)
    return new


def rename_table_sql(table: str, suffix: str) -> str:
    """The aside name for a whole (many2many relation) table."""
    return rename_column_sql(table, table, suffix)


def render_pre_migration(table: str, columns: Iterable[str], stamp: str) -> str | None:
    """A migration that renames each of ``columns`` aside, if still present."""
    return render_pre_migrations([(table, column) for column in columns], (), stamp)


def render_pre_migrations(
    columns: Iterable[tuple[str, str]],
    relation_tables: Iterable[str],
    stamp: str,
) -> str | None:
    """One migration for everything one apply removes.

    ``columns`` is ``(table, column)`` pairs across *every* model the apply
    touches: an apply writes a single script, so a script per model under the
    same path would leave only the last model's renames. ``relation_tables``
    are many2many relation tables: a many2many has no column on the model's
    own table, and removing the field drops the relation table instead, so
    that is what has to be renamed aside for its links to survive.
    """
    columns = sorted(set(columns))
    relation_tables = sorted(set(relation_tables))
    if not columns and not relation_tables:
        return None
    suffix = suffix_for(stamp)
    lines = [
        HEADER,
        "",
        "def migrate(cr, version):",
        "    if not version:",
        "        return",
    ]
    for table, column in columns:
        target = rename_column_sql(table, column, suffix)
        lines.extend(
            [
                "    cr.execute(",
                '        """',
                "        DO $$",
                "        BEGIN",
                "            IF EXISTS (",
                "                SELECT 1 FROM information_schema.columns",
                "                WHERE table_schema = current_schema()",
                "                AND table_name = '%s' AND column_name = '%s'"
                % (table, column),
                "            ) THEN",
                '                ALTER TABLE "%s" RENAME COLUMN "%s" TO "%s";'
                % (table, column, target),
                "            END IF;",
                "        END $$;",
                '        """',
                "    )",
            ]
        )
    for table in relation_tables:
        target = rename_table_sql(table, suffix)
        lines.extend(
            [
                "    cr.execute(",
                '        """',
                "        DO $$",
                "        BEGIN",
                "            IF EXISTS (",
                "                SELECT 1 FROM information_schema.tables",
                "                WHERE table_schema = current_schema()",
                "                AND table_name = '%s'" % table,
                "            ) THEN",
                '                ALTER TABLE "%s" RENAME TO "%s";' % (table, target),
                "            END IF;",
                "        END $$;",
                '        """',
                "    )",
            ]
        )
    return "\n".join(lines) + "\n"


def bump_version(version: str) -> str:
    """The next version: the last numeric component, plus one.

    Odoo runs ``migrations/<v>/pre-*.py`` only when ``installed < v <=
    manifest`` (``odoo/modules/migration.py``), so a script filed under the
    version that is already installed never runs. A destructive apply
    therefore moves the package to a new version and files its script there.
    """
    parts = (version or "").split(".")
    if parts and parts[-1].isdigit():
        parts[-1] = str(int(parts[-1]) + 1)
        return ".".join(parts)
    return "%s.1" % version if version else "1.0.1"


def migration_path(version: str, stamp: str) -> str:
    """Odoo looks for ``migrations/<version>/pre-*.py``."""
    return "migrations/%s/pre-builder-%s.py" % (version, stamp)


def is_migration_path(path: str) -> bool:
    """Whether ``path`` is one of a package's migration scripts.

    They are written once, by the apply that needs them, and belong to the
    package's history from then on: no later render produces them again, so
    a pruning write must not read their absence as "deleted".
    """
    return path.startswith("migrations/")
