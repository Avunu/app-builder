"""Generate the pre-migration that keeps a removed field's data.

Measured, not assumed (``tests/e2e/probe_reimport.py``): dropping a field from
a generated model file **drops its column and its data**. Reflection stops
reflecting the field, ``_process_end`` unlinks the ``ir.model.fields`` row, and
``IrModelFields.unlink`` calls ``_drop_column`` -- which issues
``ALTER TABLE ... DROP COLUMN ... CASCADE``, taking the m2m relation table too.

That is ordinary Odoo behaviour for any addon, and the builder cannot change it.
What it can do is get there first. ``migrate_module(package, 'pre')`` runs at
``loading.py`` well before ``_process_end``, so a pre-migration that renames the
column aside leaves nothing for ``_drop_column`` to find: it drops no column,
the metadata row is correctly removed, and the data survives under a name a
human can go and look at.

Pure string generation, no ``odoo`` import, so it is testable without a
database.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable

HEADER = (
    "# Generated by App Builder.\n"
    "#\n"
    "# Removing a field from a model drops its column and its data. This runs\n"
    "# before Odoo gets there and renames the column aside instead, so nothing\n"
    "# is lost -- inspect it, then drop it by hand when you are sure.\n"
)


def suffix_for(stamp: str) -> str:
    """A stable, sortable, obviously-not-a-real-field suffix."""
    return "builder_removed_%s" % stamp


def rename_column_sql(table: str, column: str, suffix: str) -> str:
    new = "%s_%s" % (column, suffix)
    # 63 is the Postgres identifier limit; truncating the *original* part keeps
    # the marker, which is what makes the leftover findable.
    if len(new) > 63:
        keep = 63 - len(suffix) - 1
        new = "%s_%s" % (column[:keep], suffix)
    return new


def render_pre_migration(table: str, columns: Iterable[str], stamp: str) -> str | None:
    """A migration that renames each of ``columns`` aside, if still present."""
    if not columns:
        return None
    suffix = suffix_for(stamp)
    lines = [
        HEADER,
        "",
        "def migrate(cr, version):",
        "    if not version:",
        "        return",
    ]
    for column in sorted(columns):
        target = rename_column_sql(table, column, suffix)
        lines.extend(
            [
                "    cr.execute(",
                '        """',
                "        DO $$",
                "        BEGIN",
                "            IF EXISTS (",
                "                SELECT 1 FROM information_schema.columns",
                "                WHERE table_name = '%s' AND column_name = '%s'"
                % (table, column),
                "            ) THEN",
                '                ALTER TABLE "%s" RENAME COLUMN "%s" TO "%s";'
                % (table, column, target),
                "            END IF;",
                "        END $$;",
                '        """',
                "    )",
            ]
        )
    return "\n".join(lines) + "\n"


def migration_path(version: str, stamp: str) -> str:
    """Odoo looks for ``migrations/<version>/pre-*.py``."""
    return "migrations/%s/pre-builder-%s.py" % (version, stamp)
