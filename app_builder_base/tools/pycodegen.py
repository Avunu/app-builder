"""Generate a real Python model class from ``ir.model`` metadata.

This is the transformation Odoo Studio cannot do: a customization that started
life in a visual builder becomes an ordinary ``models.Model`` subclass that a
developer owns outright. Two details make it lossless rather than a rewrite:

* the xmlids Odoo's reflection assigns to a code-defined model and its fields
  are *identical* to the ones the studio emitted in XML (``model_xmlid`` /
  ``field_xmlid`` / ``selection_xmlid``), so nothing is orphaned and the table
  and its data are untouched;
* a manual field's ``compute`` -- a sandboxed string evaluated by
  ``make_compute`` -- is promoted to a real method carrying a real
  ``@api.depends``, which is strictly more capable than what it replaces.
"""

import json
import re

HEADER = (
    "# Generated by App Builder from the visual builder.\n"
    "# This is now ordinary source code: edit it freely. The builder will stop\n"
    "# emitting XML for this model and will not overwrite this file.\n"
)

# Field constructor per ir.model.fields.ttype.
FIELD_CLASSES = {
    "binary": "Binary",
    "boolean": "Boolean",
    "char": "Char",
    "date": "Date",
    "datetime": "Datetime",
    "float": "Float",
    "html": "Html",
    "integer": "Integer",
    "json": "Json",
    "many2many": "Many2many",
    "many2one": "Many2one",
    "many2one_reference": "Many2oneReference",
    "monetary": "Monetary",
    "one2many": "One2many",
    "properties": "Properties",
    "reference": "Reference",
    "selection": "Selection",
    "text": "Text",
}

# Emission order for keyword arguments, so regenerating is diff-stable.
KWARG_ORDER = (
    "string",
    "related",
    "compute",
    "inverse_name",
    "relation",
    "column1",
    "column2",
    "selection",
    "currency_field",
    "size",
    "domain",
    "ondelete",
    "required",
    "readonly",
    "store",
    "index",
    "copy",
    "translate",
    "group_expand",
    "help",
)

_ORDER_INDEX = {name: i for i, name in enumerate(KWARG_ORDER)}


def class_name_for(model_name):
    """``x_studio_project`` -> ``XStudioProject``."""
    parts = re.split(r"[._]+", model_name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def module_file_for(model_name):
    """``x.studio.project`` -> ``x_studio_project.py``."""
    return "%s.py" % model_name.replace(".", "_")


def _indent(text, spaces):
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else "" for line in text.splitlines())


def _py(value):
    """Render a literal, preferring double quotes.

    ``repr`` would emit single quotes, which reads as inconsistent next to the
    double-quoted lines we write by hand and churns the diff if the file is ever
    run through a formatter. ``json.dumps`` gives correct escaping and the right
    quote style for strings; everything else falls back to ``repr``.
    """
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return repr(value)


def _compute_method_name(field_name):
    return "_compute_%s" % field_name


def _common_kwargs(field):
    """Attributes that mean the same thing whatever the field's type."""
    kwargs = {}
    if field.field_description:
        kwargs["string"] = _py(field.field_description)
    if field.help:
        kwargs["help"] = _py(field.help)
    if field.required:
        kwargs["required"] = "True"
    if field.readonly:
        kwargs["readonly"] = "True"
    elif field.compute or field.related:
        # Python defaults computed and related fields to readonly=True, while a
        # manual field's `readonly` is a plain Boolean defaulting to False
        # (ir_model.py:577). Staying silent would quietly make every graduated
        # computed field uneditable.
        kwargs["readonly"] = "False"
    if field.index:
        kwargs["index"] = "True"
    if field.related:
        kwargs["related"] = _py(field.related)
    if not field.copied and not field.compute and not field.related:
        # 'copy' defaults to True for a plain field but already False for a
        # computed or related one, so only state it where it actually differs.
        kwargs["copy"] = "False"
    return kwargs


def _scalar_kwargs(field):
    """Attributes only meaningful on a particular scalar type."""
    ttype = field.ttype
    kwargs = {}
    if ttype in ("char", "text", "html") and field.translate:
        kwargs["translate"] = "True"
    if ttype == "char" and field.size:
        kwargs["size"] = str(field.size)
    if ttype == "monetary" and field.currency_field:
        kwargs["currency_field"] = _py(field.currency_field)
    return kwargs


def _relational_kwargs(field):
    ttype = field.ttype
    if ttype not in ("many2one", "one2many", "many2many"):
        return {}

    kwargs = {"comodel_name": _py(field.relation)}
    if field.domain and field.domain not in ("[]", False):
        kwargs["domain"] = _py(field.domain)
    if ttype == "many2one" and field.on_delete:
        kwargs["ondelete"] = _py(field.on_delete)
    if ttype == "one2many" and field.relation_field:
        kwargs["inverse_name"] = _py(field.relation_field)
    if ttype == "many2many":
        for attr, key in (
            ("relation_table", "relation"),
            ("column1", "column1"),
            ("column2", "column2"),
        ):
            if field[attr]:
                kwargs[key] = _py(field[attr])
    return kwargs


def _selection_kwargs(field, selections):
    if field.ttype not in ("selection", "reference"):
        return {}
    # Always emit, even when empty: fields.Selection() with no selection
    # argument raises at registry build time, so omitting it would produce a
    # module that cannot be imported at all.
    pairs = ", ".join("(%s, %s)" % (_py(s.value), _py(s.name)) for s in selections)
    return {"selection": "[%s]" % pairs}


def _compute_kwargs(field):
    """compute/store/group_expand, where Python and manual defaults disagree."""
    kwargs = {}
    if field.group_expand:
        # Only many2one takes the helper-name form (ir_model.py:1332); for a
        # selection the manual layer passes the boolean straight through, and
        # the string would be looked up as a method that does not exist.
        kwargs["group_expand"] = (
            _py("_read_group_expand_full") if field.ttype == "many2one" else "True"
        )
    if field.compute:
        kwargs["compute"] = _py(_compute_method_name(field.name))
        # 'store' defaults to False for computed fields in Python, but manual
        # computed fields default it to True -- so it must be explicit.
        kwargs["store"] = "True" if field.store else "False"
    elif field.related:
        # Same asymmetry: a related field is not stored by default in Python.
        kwargs["store"] = "True" if field.store else "False"
    elif not field.store:
        kwargs["store"] = "False"
    return kwargs


def _field_kwargs(field, selections):
    """Build the keyword arguments for one field, as ``{name: source_text}``."""
    kwargs = {}
    kwargs.update(_common_kwargs(field))
    kwargs.update(_scalar_kwargs(field))
    kwargs.update(_relational_kwargs(field))
    kwargs.update(_selection_kwargs(field, selections))
    kwargs.update(_compute_kwargs(field))
    return kwargs


def _render_field(field, selections):
    kwargs = _field_kwargs(field, selections)
    cls = FIELD_CLASSES.get(field.ttype)
    if cls is None:
        return None

    # comodel_name is the conventional first positional argument.
    positional = []
    if "comodel_name" in kwargs:
        positional.append(kwargs.pop("comodel_name"))
    if "selection" in kwargs and field.ttype in ("selection", "reference"):
        positional.append(kwargs.pop("selection"))

    ordered = sorted(
        kwargs.items(),
        key=lambda kv: (_ORDER_INDEX.get(kv[0], len(KWARG_ORDER)), kv[0]),
    )
    args = positional + ["%s=%s" % (k, v) for k, v in ordered]

    single = "    %s = fields.%s(%s)" % (field.name, cls, ", ".join(args))
    if len(single) <= 88:
        return single
    body = "".join("        %s,\n" % a for a in args)
    return "    %s = fields.%s(\n%s    )" % (field.name, cls, body)


def _render_compute(field):
    """Promote a sandboxed compute string to a real method."""
    depends = [d.strip() for d in (field.depends or "").split(",") if d.strip()]
    lines = []
    if depends:
        lines.append("    @api.depends(%s)" % ", ".join(_py(d) for d in depends))
    lines.append("    def %s(self):" % _compute_method_name(field.name))
    body = (field.compute or "").strip("\n")
    if body.strip():
        lines.append(_indent(body, 8))
    else:
        lines.append("        pass")
    return "\n".join(lines)


def render_model(model, fields_):
    """Render the full source of a module file for ``model``.

    ``fields_`` is the manual field recordset to emit; base/magic columns are
    excluded by the caller because Odoo declares those itself.
    """
    ordered = sorted(fields_, key=lambda f: f.name)
    computed = [f for f in ordered if f.compute]

    lines = [HEADER, ""]
    imports = ["fields", "models"]
    if computed:
        imports.insert(0, "api")
    lines.append("from odoo import %s" % ", ".join(imports))
    lines.append("")
    lines.append("")
    # Transience is expressed by the base class in Python, not by an attribute.
    base = "models.TransientModel" if model.transient else "models.Model"
    lines.append("class %s(%s):" % (class_name_for(model.model), base))
    lines.append("    _name = %s" % _py(model.model))
    lines.append("    _description = %s" % _py(model.name or model.model))
    if model.order and model.order != "id":
        lines.append("    _order = %s" % _py(model.order))

    names = {f.name for f in ordered}
    # A custom model gets _rec_name='x_name' for free only while it is _custom
    # (models.py:3700). Once it is a real class that magic is gone, so the
    # convention has to be written down or display_name silently breaks.
    if "x_name" in names and "name" not in names:
        lines.append('    _rec_name = "x_name"')
    if "x_active" in names and "active" not in names:
        lines.append('    _active_name = "x_active"')
    lines.append("")

    skipped = []
    for field in ordered:
        # (sequence, value), matching the XML serializer. Sorting on sequence
        # alone leaves ties broken by record id, which is not stable across
        # databases and would disagree with the file the same data produces.
        selections = field.selection_ids.sorted(key=lambda s: (s.sequence, s.value))
        rendered = _render_field(field, selections)
        if rendered is None:
            skipped.append(field.name)
            continue
        lines.append(rendered)

    for field in computed:
        lines.append("")
        lines.append(_render_compute(field))

    if skipped:
        lines.append("")
        lines.append(
            "    # App Builder could not express these field types in Python: %s"
            % ", ".join(skipped)
        )

    return "\n".join(lines).rstrip("\n") + "\n"


def render_models_init(model_names):
    """``models/__init__.py`` for the graduated models."""
    stems = sorted(name.replace(".", "_") for name in model_names)
    body = "\n".join("from . import %s" % stem for stem in stems)
    return "%s\n" % body if body else ""


def render_package_init(has_models):
    return "from . import models\n" if has_models else ""
