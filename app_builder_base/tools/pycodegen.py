"""Render a ``ModelSpec`` into the machine-owned block of a model file.

This is the *primary* output of the studio, not a one-time export, and the
block convention is what makes that safe. Only the region between the markers
is ever written; the rest of the file is bytes the studio never reads. So a
developer can add a metaclass, a property, a decorator we have never heard of,
and the builder keeps working -- which is the difference between a tool you can
keep using and an export you leave behind. Frappe's ``TypeExporter`` splices
its generated block the same way, and for the same reason.

The fixed point still holds over the block: ``parse(render(spec)) == spec`` and
``render(parse(src)) == src``.

Determinism is the whole product here, exactly as it is for the XML writer.
Keyword arguments are emitted in one declared order, never dict order; fields
in declaration order, never database order. A semantic no-op must produce an
empty diff, or every save shows up as churn in review.

``spec_from_ir_model`` is the one Odoo-aware function, used only when adopting
a model that already exists as metadata. Everything else is pure.
"""

import json
import re

from . import modelspec
from .modelspec import ConstraintSpec, FieldSpec, ModelSpec, SelectionSpec

HEADER = (
    "# Generated by App Builder. Only the marked block below is machine-owned;\n"
    "# the builder rewrites it on every save and never reads the rest. Add\n"
    "# methods, decorators, imports and anything else freely outside it.\n"
)

MAX_LINE = 88

# The machine-owned region, delimited exactly as Frappe's TypeExporter does it.
# Everything between these two lines is regenerated on every save; everything
# outside them is never read.
BEGIN_MARKER = "    # begin: studio-generated schema"
END_MARKER = "    # end: studio-generated schema"
MARKER_NOTE = (
    "    # Kept in sync with the builder. Edits here are read back; edits\n"
    "    # anywhere else in this file are yours and are never touched."
)

# Field constructor per ttype.
FIELD_CLASSES = {
    "binary": "Binary",
    "boolean": "Boolean",
    "char": "Char",
    "date": "Date",
    "datetime": "Datetime",
    "float": "Float",
    "html": "Html",
    "integer": "Integer",
    "many2many": "Many2many",
    "many2one": "Many2one",
    "monetary": "Monetary",
    "one2many": "One2many",
    "reference": "Reference",
    "selection": "Selection",
    "text": "Text",
}

FIELD_CLASS_TO_TTYPE = {v: k for k, v in FIELD_CLASSES.items()}

# Emission order for keyword arguments, so regenerating is diff-stable.
KWARG_ORDER = (
    "string",
    "related",
    "compute",
    "inverse_name",
    "relation",
    "column1",
    "column2",
    "currency_field",
    "size",
    "digits",
    "domain",
    "ondelete",
    "default",
    "required",
    "readonly",
    "store",
    "index",
    "copy",
    "translate",
    "tracking",
    "group_expand",
    "help",
)

_ORDER_INDEX = {name: i for i, name in enumerate(KWARG_ORDER)}

# Attribute -> kwarg, for everything that is a plain pass-through.
_SIMPLE_KWARGS = (
    ("string", "string"),
    ("help", "help"),
    ("related", "related"),
    ("domain", "domain"),
    ("ondelete", "ondelete"),
    ("currency_field", "currency_field"),
    ("group_expand", "group_expand"),
    ("inverse_name", "inverse_name"),
    ("relation_table", "relation"),
    ("column1", "column1"),
    ("column2", "column2"),
)

_BOOL_KWARGS = (
    ("required", "required"),
    ("readonly", "readonly"),
    ("index", "index"),
    ("copy", "copy"),
    ("store", "store"),
    ("translate", "translate"),
)


def class_name_for(model_name):
    """``x.studio.project`` -> ``XStudioProject``."""
    parts = re.split(r"[._]+", model_name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def module_file_for(model_name):
    """``x.studio.project`` -> ``x_studio_project.py``."""
    return "%s.py" % model_name.replace(".", "_")


def compute_method_name(field_name):
    return "_compute_%s" % field_name


def _indent(text, spaces):
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else "" for line in text.splitlines())


def _py(value):
    """Render a literal, preferring double quotes.

    ``repr`` would emit single quotes, which reads as inconsistent next to the
    double-quoted lines we write by hand and churns the diff the moment the
    file meets a formatter.
    """
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return repr(value)


# -- fields --------------------------------------------------------------


def _field_kwargs(spec_field):
    """``{kwarg: source_text}`` for one field, in no particular order."""
    kwargs = {}
    for attr, kwarg in _SIMPLE_KWARGS:
        value = getattr(spec_field, attr)
        if value is not None:
            kwargs[kwarg] = _py(value)
    for attr, kwarg in _BOOL_KWARGS:
        value = getattr(spec_field, attr)
        if value is not None:
            kwargs[kwarg] = "True" if value else "False"
    if spec_field.size is not None:
        kwargs["size"] = str(spec_field.size)
    if spec_field.digits is not None:
        kwargs["digits"] = "(%d, %d)" % spec_field.digits
    if spec_field.tracking is not None:
        kwargs["tracking"] = (
            "True" if spec_field.tracking is True else str(spec_field.tracking)
        )
    if spec_field.default is not None:
        # Verbatim source: a literal, or a lambda the user wrote.
        kwargs["default"] = spec_field.default
    if spec_field.compute is not None:
        kwargs["compute"] = _py(spec_field.compute)
    for key, value in spec_field.extra:
        kwargs[key] = value
    return kwargs


def _render_field(spec_field):
    cls = FIELD_CLASSES.get(spec_field.ttype)
    if cls is None:
        return None
    kwargs = _field_kwargs(spec_field)

    # comodel_name and selection are the conventional positional arguments.
    positional = []
    if spec_field.comodel is not None:
        positional.append(_py(spec_field.comodel))
    if spec_field.ttype in ("selection", "reference"):
        # Always emitted, even when empty: fields.Selection() with no argument
        # raises at registry build, so omitting it produces a module that
        # cannot be imported at all.
        pairs = ", ".join(
            "(%s, %s)" % (_py(s.value), _py(s.label)) for s in spec_field.selection
        )
        positional.append("[%s]" % pairs)

    ordered = sorted(
        kwargs.items(),
        key=lambda kv: (_ORDER_INDEX.get(kv[0], len(KWARG_ORDER)), kv[0]),
    )
    args = positional + ["%s=%s" % (k, v) for k, v in ordered]

    single = "    %s = fields.%s(%s)" % (spec_field.name, cls, ", ".join(args))
    if len(single) <= MAX_LINE:
        return single
    body = "".join("        %s,\n" % a for a in args)
    return "    %s = fields.%s(\n%s    )" % (spec_field.name, cls, body)


def _render_compute(spec_field):
    lines = []
    if spec_field.depends:
        lines.append(
            "    @api.depends(%s)" % ", ".join(_py(d) for d in spec_field.depends)
        )
    lines.append("    def %s(self):" % spec_field.compute)
    body = (spec_field.compute_body or "").strip("\n")
    lines.append(_indent(body, 8) if body.strip() else "        pass")
    return "\n".join(lines)


# -- model ---------------------------------------------------------------


def _needs_api(spec):
    return bool(any(f.compute for f in spec.fields) or spec.sequence_code)


def _import_names(spec):
    names = {"fields", "models"}
    if _needs_api(spec):
        names.add("api")
    if spec.sequence_code:
        names.add("_")
    return names


def _render_imports(spec):
    return [
        "from odoo import %s" % ", ".join(sorted(_import_names(spec), key=_import_sort))
    ]


def _import_sort(name):
    # `_` sorts first in Odoo's own convention: `from odoo import _, api, ...`
    return (0 if name == "_" else 1, name)


def _docstring(text):
    """A class docstring holding exactly ``text``.

    Triple quotes read best, but fall back to an ordinary string literal when
    the text contains something that would break out of them -- correctness
    beats convention, and the value ends up in ``ir_model.info`` either way.
    """
    if '"' not in text and "\\" not in text and "\n" not in text:
        return '    """%s"""' % text
    return "    %s" % _py(text)


def _render_class_header(spec):
    lines = []
    if spec.extends:
        # No docstring and no `_description`: both are inherited from the model
        # being extended, and stating them again would make `ir_model.info`
        # disagree with what reflection writes -- the invariant I2 checks.
        chain = (spec.name,) + tuple(spec.inherit)
        if len(chain) == 1:
            lines.append("    _inherit = %s" % _py(spec.name))
        else:
            lines.append("    _inherit = [%s]" % ", ".join(_py(i) for i in chain))
    else:
        # The docstring is not decoration. _reflect_model_params fills
        # ir_model.info from the first docstring in the MRO, so a model without
        # one inherits mail.thread's or models.Model's -- which makes `info`
        # unpredictable and breaks the reflection-agreement invariant.
        #
        # Emitted verbatim, with no added punctuation: `info` is this string, so
        # anything we tack on here shows up in the database and the prediction
        # stops being exact.
        lines.append(_docstring(spec.description))
        lines.append("")
        lines.append("    _name = %s" % _py(spec.name))
        if spec.inherit:
            lines.append(
                "    _inherit = [%s]" % ", ".join(_py(i) for i in spec.inherit)
            )
        lines.append("    _description = %s" % _py(spec.description))
    if spec.order:
        lines.append("    _order = %s" % _py(spec.order))
    if spec.rec_name:
        lines.append("    _rec_name = %s" % _py(spec.rec_name))
    if spec.active_name:
        lines.append("    _active_name = %s" % _py(spec.active_name))
    return lines


def _render_sql_constraints(spec):
    if not spec.sql_constraints:
        return []
    lines = ["", "    _sql_constraints = ["]
    for constraint in spec.sql_constraints:
        lines.append(
            "        (%s, %s, %s),"
            % (
                _py(constraint.name),
                _py(constraint.definition),
                _py(constraint.message),
            )
        )
    lines.append("    ]")
    return lines


def _render_sequence_create(spec):
    """A create override, because ``default=`` would burn a number per form open.

    ``ir.sequence.next_by_code`` has a side effect. Calling it from a default
    consumes a number every time somebody opens the form and abandons it, which
    is why every core model that numbers records does this in ``create``.
    """
    if not (spec.sequence_code and spec.sequence_field):
        return []
    name = spec.sequence_field
    return [
        "",
        "    @api.model_create_multi",
        "    def create(self, vals_list):",
        "        for vals in vals_list:",
        '            if not vals.get(%s) or vals[%s] == _("New"):'
        % (_py(name), _py(name)),
        '                vals[%s] = self.env["ir.sequence"].next_by_code(' % _py(name),
        "                    %s" % _py(spec.sequence_code),
        '                ) or _("New")',
        "        return super().create(vals_list)",
    ]


def render_block(spec):
    """The machine-owned region: class attributes, fields, and their computes.

    Everything the builder knows how to change lives between the markers.
    Everything else in the file is the developer's and is never read, parsed or
    rewritten -- which is the whole point. A studio that has to understand the
    entire file in order to touch any of it is a studio a developer can lock
    themselves out of, which is the failure this project exists to avoid.
    """
    lines = [BEGIN_MARKER, MARKER_NOTE]
    lines.extend(_render_class_header(spec))
    lines.append("")

    skipped = []
    for spec_field in spec.fields:
        rendered = _render_field(spec_field)
        if rendered is None:
            skipped.append(spec_field.name)
            continue
        lines.append(rendered)

    lines.extend(_render_sql_constraints(spec))

    # A compute body is part of the field's definition, not behaviour bolted on
    # beside it, so it belongs to the block and stays editable in the builder.
    for spec_field in spec.fields:
        if spec_field.compute:
            lines.append("")
            lines.append(_render_compute(spec_field))

    lines.extend(_render_sequence_create(spec))

    if skipped:
        lines.append("")
        lines.append(
            "    # App Builder could not express these field types in Python: %s"
            % ", ".join(skipped)
        )

    lines.append("")
    lines.append(END_MARKER)
    return "\n".join(lines)


def render_model(spec):
    """A whole new file, for a model that does not have one yet."""
    lines = [HEADER.rstrip("\n"), ""]
    lines.extend(_render_imports(spec))
    lines.extend(["", ""])
    base = "models.TransientModel" if spec.transient else "models.Model"
    lines.append("class %s(%s):" % (spec.class_name, base))
    lines.append(render_block(spec))
    return "\n".join(lines).rstrip("\n") + "\n"


def splice_block(source, block, spec):
    """Put ``block`` where the old one was, touching nothing else.

    A pure string operation, exactly as Frappe's TypeExporter does it: find the
    markers, replace between them. The rest of the file is bytes we never look
    at, so a developer may write anything at all outside the block -- a
    metaclass, a property, a conditional import -- and the builder keeps
    working.
    """
    begin = source.find(BEGIN_MARKER)
    end = source.find(END_MARKER)
    if begin != -1 and end != -1 and end > begin:
        # No lstrip: BEGIN_MARKER carries its own indentation, and `begin`
        # points at the first space of it.
        return source[:begin] + block + source[end + len(END_MARKER) :]

    # No block yet: insert immediately after the class statement, which is
    # where a reader expects the schema to be.
    match = re.search(
        r"^class\s+%s\s*\(.*?\):[ \t]*$" % re.escape(spec.class_name),
        source,
        re.MULTILINE,
    )
    if not match:
        raise ValueError(
            "no studio block and no 'class %s(...)' to put one after" % spec.class_name
        )
    at = match.end()
    return "%s\n%s%s" % (source[:at], block, source[at:])


def ensure_imports(source, spec):
    """Widen ``from odoo import ...`` if the block now needs more than it has.

    The one edit the studio makes outside the block, and it is unavoidable:
    the block lives inside the class body while imports are module-level, so a
    field that introduces a compute needs ``api`` on a line the block cannot
    reach. Idempotent, and it only ever adds.
    """
    needed = set(_import_names(spec))
    match = re.search(r"^from odoo import (.+)$", source, re.MULTILINE)
    if not match:
        return source
    have = {name.strip() for name in match.group(1).split(",") if name.strip()}
    if needed <= have:
        return source
    merged = ", ".join(sorted(have | needed, key=_import_sort))
    return (
        source[: match.start()] + "from odoo import %s" % merged + source[match.end() :]
    )


def render_models_init(model_names):
    """``models/__init__.py`` for the package's Python models."""
    stems = sorted(name.replace(".", "_") for name in model_names)
    body = "\n".join("from . import %s" % stem for stem in stems)
    return "%s\n" % body if body else ""


def render_package_init(has_models):
    return "from . import models\n" if has_models else ""


# -- adoption: the one Odoo-aware direction ------------------------------


def spec_from_ir_model(model, fields_):
    """Seed a spec from metadata that already exists.

    Used only when adopting an ``x_`` manual model into a package. From then on
    the file is the definition and this function is never called for it again.

    The awkward parts are all Odoo-default asymmetries: a manual field's
    ``store`` and ``readonly`` are plain Booleans with their own defaults, and
    they disagree with what the Python field class would default to. Stating
    them explicitly here is what stops a graduated computed field coming back
    read-only or a stored related field coming back unstored.
    """
    specs = []
    for record in sorted(fields_, key=lambda f: f.name):
        specs.append(_field_spec_from_record(record))

    names = {f.name for f in specs}
    rec_name = None
    active_name = None
    if "x_name" in names and "name" not in names:
        # A custom model gets _rec_name='x_name' for free only while _custom is
        # set. Once it is a real class that magic is gone, so the convention
        # has to be written down or display_name silently breaks.
        rec_name = "x_name"
    if "x_active" in names and "active" not in names:
        active_name = "x_active"

    return ModelSpec(
        name=model.model,
        description=model.name or model.model,
        class_name=class_name_for(model.model),
        order=model.order if model.order and model.order != "id" else None,
        rec_name=rec_name,
        active_name=active_name,
        transient=bool(model.transient),
        fields=tuple(specs),
    )


def _field_spec_from_record(record):
    ttype = record.ttype
    computed = bool(record.compute)
    related = record.related or None

    if record.readonly:
        readonly = True
    elif computed or related:
        # Python defaults computed and related fields to readonly=True, while a
        # manual field's readonly is a Boolean defaulting to False. Silence
        # here would quietly make every adopted computed field uneditable.
        readonly = False
    else:
        readonly = None

    if computed or related:
        # Same asymmetry the other way: neither is stored by default in Python,
        # but a manual one defaults store=True.
        store = bool(record.store)
    else:
        store = False if not record.store else None

    copy = None
    if not record.copied and not computed and not related:
        # copy defaults True for a plain field and already False for a computed
        # or related one, so state it only where it differs.
        copy = False

    group_expand = None
    if record.group_expand:
        # Only many2one takes the helper-name form; for a selection the manual
        # layer passes the boolean straight through, and a string there would
        # be looked up as a method that does not exist.
        group_expand = "_read_group_expand_full" if ttype == "many2one" else True

    return FieldSpec(
        name=record.name,
        ttype=ttype,
        string=record.field_description or None,
        help=record.help or None,
        comodel=record.relation or None if ttype in modelspec.RELATIONAL else None,
        inverse_name=record.relation_field or None if ttype == "one2many" else None,
        relation_table=record.relation_table or None if ttype == "many2many" else None,
        column1=record.column1 or None if ttype == "many2many" else None,
        column2=record.column2 or None if ttype == "many2many" else None,
        domain=record.domain if record.domain not in ("[]", False, None) else None,
        ondelete=record.on_delete or None if ttype == "many2one" else None,
        selection=tuple(
            SelectionSpec(value=s.value, label=s.name, sequence=s.sequence)
            for s in record.selection_ids.sorted(key=lambda s: (s.sequence, s.value))
        ),
        size=record.size or None if ttype == "char" else None,
        currency_field=record.currency_field or None if ttype == "monetary" else None,
        translate=True
        if (ttype in ("char", "text", "html") and record.translate)
        else None,
        required=True if record.required else None,
        readonly=readonly,
        index=True if record.index else None,
        copy=copy,
        store=store,
        group_expand=group_expand,
        related=related,
        compute=compute_method_name(record.name) if computed else None,
        compute_body=record.compute or None,
        depends=tuple(
            d.strip() for d in (record.depends or "").split(",") if d.strip()
        ),
    )


