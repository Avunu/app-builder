"""Read the studio-owned block of a model file back into a ``ModelSpec``.

**Only the block.** The rest of the file is never parsed, never inspected and
never rewritten, so a developer may put anything in it -- a metaclass, a
property, a conditional import, a decorator we have never heard of -- and the
builder keeps working. That is the whole difference between a builder you can
keep using and a one-way export, and it is the convention Frappe's
``TypeExporter`` uses for the same reason.

Because the block is text we generated, it parses. A failure here is a loud,
actionable error about *our* region -- not a model that silently locks itself
out of the builder.
"""

import ast
import re
import textwrap

from . import modelspec, pycodegen
from .modelspec import (
    ConstraintSpec,
    FieldSpec,
    MethodSpec,
    ModelSpec,
    SelectionSpec,
)

# Kwargs that map straight onto a FieldSpec attribute of the same shape.
_STR_KWARGS = {
    "string": "string",
    "help": "help",
    "related": "related",
    "domain": "domain",
    "ondelete": "ondelete",
    "currency_field": "currency_field",
    "group_expand": "group_expand",
    "inverse_name": "inverse_name",
    "relation": "relation_table",
    "column1": "column1",
    "column2": "column2",
    "compute": "compute",
}

_BOOL_KWARGS = {
    "required": "required",
    "readonly": "readonly",
    "index": "index",
    "copy": "copy",
    "store": "store",
    "translate": "translate",
}

# Kwargs whose literal needs a specific type on the way in.
_LITERAL_KWARGS = {
    "size": int,
    "digits": tuple,
    "tracking": lambda v: v,
}

_MODEL_ATTRS = {
    "_name": "name",
    "_description": "description",
    "_order": "order",
    "_rec_name": "rec_name",
    "_active_name": "active_name",
}


class UnsupportedConstruct(Exception):
    """The file contains something the builder must not rewrite."""


def _literal(node):
    try:
        return ast.literal_eval(node)
    except (ValueError, SyntaxError, TypeError) as err:
        raise UnsupportedConstruct(
            "expression is not a literal: %s" % ast.unparse(node)
        ) from err


def _segment(source, node):
    """The exact source of a node, decorators included."""
    start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
    lines = source.splitlines()
    return "\n".join(lines[start - 1 : node.end_lineno])


def is_studio_generated(source):
    """Whether this file carries our header, i.e. we wrote it."""
    return source.lstrip().startswith("# Generated by App Builder")


def extract_block(source):
    """The block's source, dedented to module level, or ``None``."""
    begin = source.find(pycodegen.BEGIN_MARKER)
    end = source.find(pycodegen.END_MARKER)
    if begin == -1 or end == -1 or end <= begin:
        return None
    body = source[begin + len(pycodegen.BEGIN_MARKER) : end]
    return textwrap.dedent(body)


def parse_model(source):
    """``ModelSpec`` for the studio block in ``source``.

    Raises ``UnsupportedConstruct`` when the block is missing or unreadable.
    """
    block = extract_block(source)
    if block is None:
        raise UnsupportedConstruct(
            "no studio block found; this file is not one the builder owns"
        )
    class_name, base = _class_statement_around(source)
    # Reconstitute a class so the existing body walker can be reused verbatim.
    # The class statement is outside the block, so its name and base are read
    # from the file rather than regenerated.
    synthetic = "class %s(models.%s):\n%s" % (
        class_name,
        base,
        textwrap.indent(block, "    ") or "    pass\n",
    )
    try:
        tree = ast.parse(synthetic)
    except SyntaxError as err:
        raise UnsupportedConstruct("studio block does not parse: %s" % err) from err
    return _parse_class(synthetic, tree.body[0])


def _class_statement_around(source):
    """The name and Odoo base of the class the block sits in.

    Both live outside the block -- the class statement is the developer's --
    so they are read from the file rather than reproduced from the spec.
    """
    begin = source.find(pycodegen.BEGIN_MARKER)
    head = source[:begin] if begin != -1 else source
    matches = re.findall(r"^class\s+(\w+)\s*\((.*)$", head, re.MULTILINE)
    if not matches:
        raise UnsupportedConstruct("the studio block is not inside a class")
    name, bases = matches[-1]
    return name, "TransientModel" if "TransientModel" in bases else "Model"


def _parse_class(source, node, _unused=()):
    # The class statement itself is outside the block, so transience is read
    # from the file by the caller and defaulted here.
    transient = _base_is(node, "TransientModel")

    attrs = {}
    inherit = ()
    sql_constraints = []
    fields = []
    computes = {}
    methods = []
    sequence_code = None
    sequence_field = None

    for child in node.body:
        if isinstance(child, ast.Expr) and isinstance(child.value, ast.Constant):
            continue  # class docstring; regenerated from _description

        if isinstance(child, ast.Assign):
            target = _single_target(child)
            if target in _MODEL_ATTRS:
                attrs[_MODEL_ATTRS[target]] = _literal(child.value)
            elif target == "_inherit":
                value = _literal(child.value)
                inherit = tuple(value) if isinstance(value, list) else (value,)
            elif target == "_sql_constraints":
                sql_constraints = [
                    ConstraintSpec(*row) for row in _literal(child.value)
                ]
            elif target.startswith("_"):
                raise UnsupportedConstruct("unmodelled class attribute %s" % target)
            else:
                fields.append(_parse_field(target, child.value))
            continue

        if isinstance(child, ast.FunctionDef):
            if child.name.startswith(modelspec.STUDIO_METHOD_PREFIX):
                methods.append(_parse_method(source, child))
            elif child.name.startswith("_compute_"):
                computes[child.name] = _parse_compute(source, child)
            elif child.name == "create":
                found = _parse_sequence_create(child)
                if found:
                    sequence_field, sequence_code = found
                else:
                    raise UnsupportedConstruct(
                        "create() in the studio block is not one the builder "
                        "wrote; move it below the block, where it is yours"
                    )
            else:
                raise UnsupportedConstruct(
                    "%s() is behaviour, not schema: move it below the block, "
                    "where the builder will never touch it" % child.name
                )
            continue

        raise UnsupportedConstruct("unmodelled class-body %s" % type(child).__name__)

    fields = tuple(_attach_compute(f, computes) for f in fields)
    unclaimed = set(computes) - {f.compute for f in fields if f.compute}
    if unclaimed:
        raise UnsupportedConstruct(
            "compute method(s) with no field: %s" % ", ".join(sorted(unclaimed))
        )

    # `_inherit` with no `_name` is Odoo's own spelling for extending a model
    # rather than declaring one, and the presence of `_name` is the whole
    # discriminator: a new model with mixins has both, an extension has only
    # the one. The first entry is what is being extended; anything after it is
    # a mixin being added to it.
    extends = "name" not in attrs and bool(inherit)
    if extends:
        attrs["name"] = inherit[0]
        inherit = inherit[1:]
    if "name" not in attrs:
        raise UnsupportedConstruct("class has neither _name nor _inherit")

    return ModelSpec(
        name=attrs["name"],
        description=attrs.get("description") or ("" if extends else attrs["name"]),
        class_name=node.name,
        inherit=inherit,
        extends=extends,
        order=attrs.get("order"),
        rec_name=attrs.get("rec_name"),
        active_name=attrs.get("active_name"),
        transient=transient,
        fields=fields,
        methods=tuple(methods),
        sql_constraints=tuple(sql_constraints),
        sequence_code=sequence_code,
        sequence_field=sequence_field,
    )


def _base_is(node, name):
    for base in node.bases:
        if isinstance(base, ast.Attribute) and base.attr == name:
            return True
    return False


def _single_target(node):
    if len(node.targets) != 1 or not isinstance(node.targets[0], ast.Name):
        raise UnsupportedConstruct("only simple assignments are modelled")
    return node.targets[0].id


def _attach_compute(spec_field, computes):
    if not spec_field.compute:
        return spec_field
    found = computes.get(spec_field.compute)
    if not found:
        raise UnsupportedConstruct(
            "field %s declares compute=%r with no such method"
            % (spec_field.name, spec_field.compute)
        )
    depends, body = found
    from dataclasses import replace

    return replace(spec_field, depends=depends, compute_body=body)


def _field_ttype(name, node):
    """The ttype behind a ``fields.X(...)`` call, or refuse."""
    if not isinstance(node, ast.Call):
        raise UnsupportedConstruct("%s is not a field definition" % name)
    func = node.func
    if not (isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name)):
        raise UnsupportedConstruct("%s: unrecognised field constructor" % name)
    if func.value.id != "fields":
        raise UnsupportedConstruct("%s: not a fields.* call" % name)

    from .pycodegen import FIELD_CLASS_TO_TTYPE

    ttype = FIELD_CLASS_TO_TTYPE.get(func.attr)
    if ttype is None:
        raise UnsupportedConstruct("%s: unsupported field type %s" % (name, func.attr))
    return ttype


def _parse_positional(name, ttype, node, values):
    """comodel for relations, selection pairs for selection/reference."""
    positional = list(node.args)
    if ttype in ("many2one", "one2many", "many2many") and positional:
        values["comodel"] = _literal(positional.pop(0))
    if ttype in ("selection", "reference") and positional:
        values["selection"] = _selection(positional.pop(0))
    if positional:
        raise UnsupportedConstruct("%s: unexpected positional argument" % name)


def _parse_kwarg(name, kw, values, extra):
    if kw.arg is None:
        raise UnsupportedConstruct("%s: **kwargs is not modelled" % name)
    if kw.arg == "comodel_name":
        values["comodel"] = _literal(kw.value)
    elif kw.arg == "selection":
        values["selection"] = _selection(kw.value)
    elif kw.arg in _STR_KWARGS:
        values[_STR_KWARGS[kw.arg]] = _literal(kw.value)
    elif kw.arg in _BOOL_KWARGS:
        values[_BOOL_KWARGS[kw.arg]] = bool(_literal(kw.value))
    elif kw.arg in _LITERAL_KWARGS:
        values[kw.arg] = _LITERAL_KWARGS[kw.arg](_literal(kw.value))
    elif kw.arg == "default":
        # Verbatim: a literal, or a lambda we must not try to interpret.
        values["default"] = ast.unparse(kw.value)
    else:
        extra.append((kw.arg, ast.unparse(kw.value)))


def _parse_field(name, node):
    ttype = _field_ttype(name, node)
    values = {"name": name, "ttype": ttype}
    extra = []
    _parse_positional(name, ttype, node, values)
    for kw in node.keywords:
        _parse_kwarg(name, kw, values, extra)
    values["extra"] = tuple(extra)
    return FieldSpec(**values)


def _selection(node):
    pairs = _literal(node)
    return tuple(
        SelectionSpec(value=value, label=label, sequence=(i + 1) * 10)
        for i, (value, label) in enumerate(pairs)
    )


def _parse_method(source, node):
    """A method the builder wrote, read back verbatim.

    The prefix is the whole test. A developer's own method has no reason to
    carry it, and one that does is claiming to be the builder's -- which is a
    thing to be told about rather than to guess at, so a decorator here is
    refused for the same reason it is on a compute.
    """
    if node.decorator_list:
        raise UnsupportedConstruct(
            "%s carries a decorator the builder does not model" % node.name
        )
    doc = ast.get_docstring(node) or ""
    lines = source.splitlines()
    first = node.body[1] if doc and len(node.body) > 1 else node.body[0]
    if doc and len(node.body) == 1:
        body = ""
    else:
        body = "\n".join(lines[first.lineno - 1 : node.end_lineno])
    return MethodSpec(name=node.name, body=_dedent(body), doc=doc)


def _parse_compute(source, node):
    depends = ()
    for decorator in node.decorator_list:
        if (
            isinstance(decorator, ast.Call)
            and isinstance(decorator.func, ast.Attribute)
            and decorator.func.attr == "depends"
        ):
            depends = tuple(_literal(a) for a in decorator.args)
        else:
            raise UnsupportedConstruct(
                "%s carries a decorator the builder does not model" % node.name
            )

    lines = source.splitlines()
    body_start = node.body[0].lineno
    body = "\n".join(lines[body_start - 1 : node.end_lineno])
    return depends, _dedent(body)


def _dedent(text):
    lines = [ln for ln in text.splitlines()]
    indents = [len(ln) - len(ln.lstrip()) for ln in lines if ln.strip()]
    if not indents:
        return ""
    pad = min(indents)
    return "\n".join(ln[pad:] if ln.strip() else "" for ln in lines)


def _parse_sequence_create(node):
    """Recognise the create override we generate, and nothing else.

    Returns ``(field_name, sequence_code)`` when the body is exactly the shape
    ``_render_sequence_create`` emits, else ``None`` so the caller preserves
    the method verbatim instead.
    """
    codes = []
    fields_ = []
    for sub in ast.walk(node):
        if (
            isinstance(sub, ast.Call)
            and isinstance(sub.func, ast.Attribute)
            and sub.func.attr == "next_by_code"
            and sub.args
        ):
            try:
                codes.append(_literal(sub.args[0]))
            except UnsupportedConstruct:
                return None
        if (
            isinstance(sub, ast.Subscript)
            and isinstance(sub.slice, ast.Constant)
            and isinstance(sub.slice.value, str)
        ):
            fields_.append(sub.slice.value)
    if len(set(codes)) != 1 or not fields_:
        return None
    return fields_[0], codes[0]
